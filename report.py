"""Builds RESULTS tables (markdown) and figures from results/*.json + calib/*.json."""
import glob
import json
import os
import sys

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

from costmodel import Cfg, evaluate, load_cal

HE, GC = load_cal()
PRESETS = {"LAN 10 Gbps / 0.1 ms": (0.1, 10000), "WAN 1 Gbps / 10 ms": (10, 1000),
           "WAN 400 Mbps / 40 ms": (40, 400), "WAN 100 Mbps / 80 ms": (80, 100),
           "WAN 20 Mbps / 150 ms": (150, 20)}
BLUE, ORANGE, AQUA, MAG = "#2a78d6", "#eb6834", "#1baf7a", "#e87ba4"
INK, GRID = "#0b0b0b", "#e4e3df"
S_CORES, C_CORES = 64, 8


def load_all():
    out = {}
    for f in sorted(glob.glob("results/*_N*_m*_E*.json")):
        r = json.load(open(f))
        if "secure" in r:
            kf = f"results/kernel_{r['tag']}.json"
            if os.path.exists(kf):
                r["server_kernel_s"] = json.load(open(kf))
            out[r["tag"]] = r
    return out


def ev(res, rtt, bw, enc, **kw):
    return evaluate(res, HE, GC, Cfg(rtt, bw, None, kw.get("S", S_CORES), kw.get("C", C_CORES), enc))


def fmt_b(x):
    for u, d in (("TB", 1e12), ("GB", 1e9), ("MB", 1e6), ("KB", 1e3)):
        if x >= d:
            return f"{x / d:.2f} {u}"
    return f"{x:.0f} B"


def fmt_t(x):
    if x < 1:
        return f"{x * 1e3:.0f} ms"
    if x < 120:
        return f"{x:.1f} s"
    if x < 7200:
        return f"{x / 60:.1f} min"
    return f"{x / 3600:.1f} h"


def style(ax, xl, yl, title):
    ax.set_xlabel(xl); ax.set_ylabel(yl); ax.set_title(title, loc="left", fontsize=11, color=INK)
    ax.grid(True, color=GRID, lw=0.8); ax.set_axisbelow(True)
    for s in ("top", "right"):
        ax.spines[s].set_visible(False)


def main():
    R = load_all()
    md = []
    P = md.append
    P("# Measured / modelled performance tables (auto-generated by report.py)\n")
    P(f"Server cores = {S_CORES}, client cores = {C_CORES} (modelled per-party core counts); the machine used for "
      f"measurement has 448 cores.\n")
    # ---------- accuracy & sizes ----------
    P("## 1. Accuracy (recall@10, 1000 queries) \n")
    P("| run | N | d | m | E | secure private HNSW | exact-greedy HNSW (plaintext) | hnswlib | LSH failure rate | bucket-cap loss | queries w/ recall 1 | secure==plain emulation |")
    P("|---|---|---|---|---|---|---|---|---|---|---|---|")
    for t, r in R.items():
        a, ac = r["args"], r["accuracy"]
        P(f"| {t} | {a['N']} | {r['server_build']['sizes']['A'] and (r['server_build']['sizes']['A'] - 3) // a['s'] - 4} | {a['m']} | {a['E']} | "
          f"{ac['recall_secure_vs_float_gt']:.4f} | {ac['recall_exact_greedy_hnsw_vs_float_gt']:.4f} | {ac['recall_hnswlib_vs_quantized_gt']:.4f} | "
          f"{ac['lsh_failure_rate']:.1%} | {ac['bucket_cap_loss']:.1%} | {ac['frac_queries_recall1']:.1%} | {r['secure']['identical']}/{r['secure']['nperf']} |")
    P("\n## 2. Graph / table sizes and server preprocessing (measured)\n")
    P("| run | raw vectors | plain HNSW graph (ids) | hnswlib index | flattened server tables | theta | LSH dicts | rows U | HNSW build | import | flatten+LSH+cuckoo | server total |")
    P("|---|---|---|---|---|---|---|---|---|---|---|---|")
    for t, r in R.items():
        sz, tm = r["server_build"]["sizes"], r["server_build"]["times"]
        P(f"| {t} | {fmt_b(sz['raw_vectors_bytes'])} | {fmt_b(sz['graph_bytes_ids'])} | {fmt_b(sz['hnswlib_index_bytes'])} | "
          f"{fmt_b(sz['flattened_total_bytes'])} | {fmt_b(sz['theta_bytes'])} | {fmt_b(sz['Dtab_bytes'])} | {sz['U']} | "
          f"{fmt_t(tm['hnsw_build'])} | {fmt_t(tm['graph_import'])} | {fmt_t(tm['flatten_tables'])} | {fmt_t(tm['server_total'])} |")
    # ---------- GC sizes ----------
    P("\n## 3. Garbled-circuit sizes (exact AND counts of the executed protocol; 32 B per AND)\n")
    for t, r in R.items():
        gcm = r["secure"]["meters"][0]["gc"]
        gmax = r["secure"]["meters"][0]["gc_max"]
        P(f"**{t}**\n")
        P("| circuit | calls/query | ANDs per call | of which I/O wrapper | size per call | size per query |")
        P("|---|---|---|---|---|---|")
        tot = 0
        for n, g in gcm.items():
            per = (g["and_core"] + g["and_io"]) / g["calls"]
            tot += g["and_core"] + g["and_io"]
            P(f"| {n} | {g['calls']:.0f} | {per:,.0f} | {g['and_io'] / g['calls']:,.0f} | {fmt_b(32 * per)} | {fmt_b(32 * per * g['calls'])} |")
        P(f"| **total** | | | | | **{fmt_b(32 * tot)}** ({tot:,.0f} ANDs) |\n")
    # ---------- online performance ----------
    for enc, label in (("broadcast", "HE row selector as implemented in real_he.py (U broadcast ciphertexts per client per iteration)"),
                       ("packed", "HE row selector packed into ceil(U/slots) ciphertexts (modelled optimisation)")):
        P(f"\n## 4{'a' if enc == 'broadcast' else 'b'}. Online query performance, {label}\n")
        P("| run | network | latency | server compute | client compute (P1) | comm wait | rounds (RTT) | per-client comm (online) | server comm | throughput q/s (bottleneck) |")
        P("|---|---|---|---|---|---|---|---|---|---|")
        for t, r in R.items():
            for pn, (rtt, bw) in PRESETS.items():
                if pn not in ("LAN 10 Gbps / 0.1 ms", "WAN 100 Mbps / 80 ms"):
                    continue
                x = ev(r, rtt, bw, enc)
                P(f"| {t} | {pn} | {fmt_t(x['latency_s'])} | {fmt_t(x['latency_compute_server_s'])} | {fmt_t(x['latency_compute_client_s'])} | "
                  f"{fmt_t(x['latency_comm_s'])} | {x['rtts']:.0f} | {fmt_b(max(x['online_bytes_client']))} | {fmt_b(x['online_bytes_server'])} | "
                  f"{x['qps']:.4f} ({x['bottleneck']}) |")
    P("\n## 5. Per-party breakdown (online, packed-HE variant, WAN 100 Mbps / 80 ms)\n")
    for t, r in R.items():
        x = ev(r, 80, 100, "packed")
        P(f"**{t}**\n")
        P("| server compute part | time |\n|---|---|")
        for k, v in x["t_server_parts"].items():
            P(f"| {k} | {fmt_t(v)} |")
        P("\n| client compute part (P1 / other clients) | P1 | client 2 |\n|---|---|---|")
        for k, v in x["t_client_parts"].items():
            P(f"| {k} | {fmt_t(v[0])} | {fmt_t(v[1])} |")
        P("\n| comm category | per-client (max) | server |\n|---|---|---|")
        for k in sorted(set(x["bytes_by_cat_client"]) | set(x["bytes_by_cat_server"])):
            P(f"| {k} | {fmt_b(max(x['bytes_by_cat_client'].get(k, [0])))} | {fmt_b(x['bytes_by_cat_server'].get(k, 0))} |")
        P(f"\nwait: server idle {fmt_t(x['server_wait_s'])} of {fmt_t(x['latency_s'])} (network {fmt_t(x['wait_comm_s'])}, waiting for clients {fmt_t(x['server_wait_peer_s'])}); "
          f"P1 idle {fmt_t(x['client_wait_s'][0])} (network {fmt_t(x['wait_comm_s'])}, waiting for server {fmt_t(x['client_wait_peer_s'][0])}); "
          f"other clients idle {fmt_t(x['client_wait_s'][1])}.\n")
    P("\n## 6. Offline phase per query + one-time setup (modelled from calibrated HE/GC/OT costs, packed variant)\n")
    P("| run | GC garbling (server) | GC tables to P1 | ROT/OT (server / client) | Beaver triples | read-correlation (server) | read-correlation (client) | offline bytes per client | HE keygen per client |")
    P("|---|---|---|---|---|---|---|---|---|")
    for t, r in R.items():
        o = ev(r, 0.1, 10000, "packed")["offline"]
        P(f"| {t} | {fmt_t(o['gc_garble_server_s'])} | {fmt_b(o['gc_table_bytes'])} | {fmt_t(o['rot_gen_s_server'])} / {fmt_t(o['rot_gen_s_client'])} | "
          f"{o['triples']:,.0f} | {fmt_t(o['read_corr_server_s'])} | {fmt_t(o['read_corr_client_s'])} | {fmt_b(o['offline_bytes_client'])} | {fmt_t(o['keygen_client_s'])} |")

    # ---------- sweeps + figures ----------
    figs = []
    keys = [k for k in R if k.endswith("_m4_E64") and R[k]["args"]["N"] == 100000] or list(R)[:2]
    cols = {k: c for k, c in zip(keys, (BLUE, ORANGE, AQUA, MAG))}
    bws = np.array([10, 20, 50, 100, 200, 400, 1000, 5000, 10000])
    rtts = np.array([0.1, 5, 10, 20, 40, 80, 150, 300])
    fig, axs = plt.subplots(2, 2, figsize=(12, 8.5), facecolor="white")
    P("\n## 7. WAN sweeps (packed-HE variant; broadcast variant dashed)\n")
    P("| run | variant | RTT=40 ms: BW 20 / 100 / 1000 Mbps latency | BW=1 Gbps: RTT 10 / 80 / 300 ms latency | throughput q/s at 20 / 100 / 1000 Mbps |\n|---|---|---|---|---|")
    for k in keys:
        r = R[k]
        for enc, ls in (("packed", "-"), ("broadcast", "--")):
            lat_bw = [ev(r, 40, b, enc)["latency_s"] for b in bws]
            lat_rtt = [ev(r, t, 1000, enc)["latency_s"] for t in rtts]
            qps_bw = [ev(r, 40, b, enc)["qps"] for b in bws]
            comm_bw = [ev(r, 40, b, enc)["latency_comm_s"] for b in bws]
            axs[0, 0].plot(bws, lat_bw, ls, color=cols[k], lw=2, label=f"{k} ({enc})")
            axs[0, 1].plot(rtts, lat_rtt, ls, color=cols[k], lw=2, label=f"{k} ({enc})")
            axs[1, 0].plot(bws, qps_bw, ls, color=cols[k], lw=2, label=f"{k} ({enc})")
            f = lambda b: ev(r, 40, b, enc)["latency_s"]
            g = lambda t: ev(r, t, 1000, enc)["latency_s"]
            q = lambda b: ev(r, 40, b, enc)["qps"]
            P(f"| {k} | {enc} | {fmt_t(f(20))} / {fmt_t(f(100))} / {fmt_t(f(1000))} | {fmt_t(g(10))} / {fmt_t(g(80))} / {fmt_t(g(300))} | "
              f"{q(20):.4f} / {q(100):.4f} / {q(1000):.4f} |")
    for ax, (xl, yl, tt) in zip(axs.ravel(), [("bandwidth per link (Mbps)", "latency (s)", "Latency vs bandwidth (RTT 40 ms)"),
                                              ("RTT (ms)", "latency (s)", "Latency vs round-trip time (1 Gbps)"),
                                              ("bandwidth per link (Mbps)", "queries / s", "Throughput vs bandwidth (RTT 40 ms)")]):
        style(ax, xl, yl, tt)
        ax.set_xscale("log"); ax.set_yscale("log")
    axs[0, 0].legend(fontsize=7, frameon=False)
    # stacked breakdown of latency (packed) at 100 Mbps / 80 ms
    ax = axs[1, 1]
    comp = ["server compute", "client compute", "round-trip latency", "data transfer"]
    cc = [BLUE, ORANGE, AQUA, MAG]
    for xi, k in enumerate(keys):
        x = ev(R[k], 80, 100, "packed")
        vals = [x["latency_compute_server_s"], x["latency_compute_client_s"], x["latency_rounds_s"], x["latency_transfer_s"]]
        bot = 0
        for v, c, nme in zip(vals, cc, comp):
            ax.bar(xi, v, bottom=bot, color=c, width=0.55, edgecolor="white", lw=2, label=nme if xi == 0 else None)
            bot += v
    ax.set_xticks(range(len(keys))); ax.set_xticklabels(keys, fontsize=8)
    style(ax, "", "seconds", "Latency breakdown (100 Mbps, 80 ms RTT, packed HE)")
    ax.legend(fontsize=8, frameon=False)
    plt.tight_layout(); plt.savefig("results/fig_wan.png", dpi=130); plt.close()
    figs.append("results/fig_wan.png")

    # ---------- scaling in N, m, E ----------
    P("\n## 8. Scaling (packed-HE variant, LAN and WAN 100 Mbps/80 ms)\n")
    P("| run | recall@10 | latency LAN | latency WAN | online comm / client | offline comm / client | GC / query | server compute (64c) | P1 compute (8c) |\n|---|---|---|---|---|---|---|---|---|")
    for t, r in R.items():
        a = ev(r, 0.1, 10000, "packed"); b = ev(r, 80, 100, "packed")
        P(f"| {t} | {r['accuracy']['recall_secure_vs_float_gt']:.3f} | {fmt_t(a['latency_s'])} | {fmt_t(b['latency_s'])} | "
          f"{fmt_b(max(a['online_bytes_client']))} | {fmt_b(a['offline']['offline_bytes_client'] + max(a['offline_gc_bytes_client'] if False else [0]))} | "
          f"{fmt_b(a['gc_bytes'])} | {fmt_t(a['latency_compute_server_s'])} | {fmt_t(a['latency_compute_client_s'])} |")
    # lagrange
    if os.path.exists("results/lagrange_onehot.json"):
        L = json.load(open("results/lagrange_onehot.json"))
        P("\n## 9. Lagrange one-hot conversion (Sec. 4) cost vs domain size n (measured, per client, single core)\n")
        P("| n | time per conversion | table memory |\n|---|---|---|")
        for row in L["rows"]:
            P(f"| {row['n']} | {fmt_t(row['call_s'])} | {fmt_b(row['table_bytes'])} |")
        P(f"\nEmpirical exponent ~ n^{L['exponent']:.1f}.\n")
    open("results/TABLES.md", "w").write("\n".join(md))
    print("wrote results/TABLES.md and", figs)


if __name__ == "__main__":
    main()
